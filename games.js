(() => {
    const root = document.documentElement;
    const languageButtons = document.querySelectorAll('[data-language]');
    const themeButton = document.getElementById('theme-toggle');
    const systemTheme = window.matchMedia('(prefers-color-scheme: dark)');
    const textNodes = [];
    const attributes = [];
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) {
        if (node.parentElement.closest('script, style, .preferences')) continue;
        const key = node.nodeValue.trim();
        if (Object.prototype.hasOwnProperty.call(gameTranslations, key)) {
            textNodes.push({ node, original: node.nodeValue, key });
        }
    }
    document.querySelectorAll('[alt], [title], [aria-label], meta[name="description"]').forEach(element => {
        ['alt', 'title', 'aria-label', 'content'].forEach(name => {
            const original = element.getAttribute(name);
            if (Object.prototype.hasOwnProperty.call(gameTranslations, original)) {
                attributes.push({ element, name, original });
            }
        });
    });
    function save(key, value) {
        try { localStorage.setItem(key, value); } catch (_) { /* Session-only fallback. */ }
    }
    function setLanguage(language) {
        root.lang = language;
        textNodes.forEach(({ node, original, key }) => {
            node.nodeValue = language === 'en' ? original.replace(key, gameTranslations[key]) : original;
        });
        attributes.forEach(({ element, name, original }) => {
            element.setAttribute(name, language === 'en' ? gameTranslations[original] : original);
        });
        languageButtons.forEach(button => {
            button.setAttribute('aria-pressed', String(button.dataset.language === language));
        });
        themeButton.setAttribute('aria-label', language === 'en' ? 'Dark mode' : '深色模式');
        updateThemeLabel();
    }
    function isDark() {
        return root.dataset.theme === 'dark' || (root.dataset.theme === 'system' && systemTheme.matches);
    }
    function updateThemeLabel() {
        themeButton.title = root.lang === 'en'
            ? (isDark() ? 'Switch to light mode' : 'Switch to dark mode')
            : (isDark() ? '切換至淺色模式' : '切換至深色模式');
    }
    function setTheme(theme) {
        root.dataset.theme = theme;
        const dark = isDark();
        themeButton.dataset.active = dark ? 'second' : 'first';
        themeButton.setAttribute('aria-pressed', String(dark));
        updateThemeLabel();
        document.querySelector('meta[name="theme-color"]').content = dark ? '#171c1a' : '#f4efe6';
    }
    let language = 'zh-Hant';
    try {
        if (localStorage.getItem('games-language') === 'en') language = 'en';
    } catch (_) { /* Keep the default language. */ }
    setLanguage(language);
    setTheme(root.dataset.theme || 'system');
    languageButtons.forEach(button => {
        button.addEventListener('click', () => {
            const next = button.dataset.language;
            setLanguage(next);
            save('games-language', next);
        });
    });
    themeButton.addEventListener('click', () => {
        const next = isDark() ? 'light' : 'dark';
        setTheme(next);
        save('games-theme', next);
    });
    systemTheme.addEventListener('change', () => {
        if (root.dataset.theme === 'system') setTheme('system');
    });
    document.querySelector('.preferences').hidden = false;
})();
